    TOTAL_FILAS          NUMBER(10) DEFAULT 0 NOT NULL,
    TOTAL_COLUMNAS       NUMBER(6) DEFAULT 0 NOT NULL,
    TAMANO_BYTES         NUMBER(15) DEFAULT 0 NOT NULL,
