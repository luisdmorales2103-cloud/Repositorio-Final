-- ==============================================================================
-- VISTA ANALÍTICA RESUMEN: VW_DW_PROYECTO_RESUMEN
-- ==============================================================================
CREATE OR REPLACE VIEW VW_DW_PROYECTO_RESUMEN AS
SELECT 
    p.PROYECTO_ID,
    p.CODIGO_PROYECTO,
    p.NOMBRE AS NOMBRE_PROYECTO,
    p.CATEGORIA,
    p.ESTADO,
    p.CREADO_POR,
    p.FECHA_CREACION,
    COUNT(DISTINCT d.DATASET_ID) AS TOTAL_DATASETS,
    NVL(SUM(d.TOTAL_FILAS), 0) AS TOTAL_FILAS_ACUMULADAS,
    NVL(SUM(d.TAMANO_BYTES), 0) AS TOTAL_BYTES_ALMACENADOS,
    COUNT(DISTINCT a.ACCESO_ID) AS TOTAL_MIEMBROS,
    COUNT(DISTINCT g.GRAFICO_ID) AS TOTAL_GRAFICOS,
    COUNT(DISTINCT c.CARGA_ID) AS TOTAL_CARGAS_REALIZADAS
FROM DW_PROYECTOS p
LEFT JOIN DW_DATASETS d ON p.PROYECTO_ID = d.PROYECTO_ID
LEFT JOIN DW_ACCESOS a ON p.PROYECTO_ID = a.PROYECTO_ID
LEFT JOIN DW_GRAFICOS g ON p.PROYECTO_ID = g.PROYECTO_ID
LEFT JOIN DW_CARGAS c ON p.PROYECTO_ID = c.PROYECTO_ID
GROUP BY 
    p.PROYECTO_ID, p.CODIGO_PROYECTO, p.NOMBRE, p.CATEGORIA, 
    p.ESTADO, p.CREADO_POR, p.FECHA_CREACION;

COMMIT;
