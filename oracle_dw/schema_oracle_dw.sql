-- ==============================================================================
-- TABLA 6: DW_FILAS (ALMACENAMIENTO HÍBRIDO RAW / STAGING / ANALYTICS)
-- Nota: En Oracle Enterprise, se recomienda particionar por LIST o HASH en PROYECTO_ID.
-- Combina almacenamiento de documentos crudos (CLOB/JSON) con columnas fuertemente tipadas
-- (NUMERIC_01..10, VARCHAR_01..10, DATE_01..05) para rendimiento óptimo de agregación.
-- ==============================================================================
CREATE TABLE DW_FILAS (
    FILA_ID              VARCHAR2(36) NOT NULL,
    PROYECTO_ID          VARCHAR2(36) NOT NULL,
    DATASET_ID           VARCHAR2(36) NOT NULL,
    CARGA_ID             VARCHAR2(36) NOT NULL,
    NUMERO_FILA          NUMBER(10) NOT NULL,
    CAPA                 VARCHAR2(20) DEFAULT 'ANALYTICS' NOT NULL,
    
    -- Capa RAW y STAGING: JSON completo sin truncamiento
    PAYLOAD_RAW          CLOB,
    PAYLOAD_STAGING      CLOB,

    -- Capa ANALYTICS: Proyección columnar tipada para indexación y agregaciones analíticas de alta velocidad
    NUMERIC_01           NUMBER(18,4),
    NUMERIC_02           NUMBER(18,4),
    NUMERIC_03           NUMBER(18,4),
    NUMERIC_04           NUMBER(18,4),
    NUMERIC_05           NUMBER(18,4),
    NUMERIC_06           NUMBER(18,4),
    NUMERIC_07           NUMBER(18,4),
    NUMERIC_08           NUMBER(18,4),
    
    VARCHAR_01           VARCHAR2(255),
    VARCHAR_02           VARCHAR2(255),
    VARCHAR_03           VARCHAR2(255),
    VARCHAR_04           VARCHAR2(255),
    VARCHAR_05           VARCHAR2(255),
    VARCHAR_06           VARCHAR2(255),
    VARCHAR_07           VARCHAR2(255),
    VARCHAR_08           VARCHAR2(255),
    
    DATE_01              DATE,
    DATE_02              DATE,
    DATE_03              DATE,
    
    ESTADO_VALIDACION    VARCHAR2(20) DEFAULT 'VALIDA' NOT NULL,
    FECHA_REGISTRO       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_DW_FILAS PRIMARY KEY (FILA_ID),
    CONSTRAINT FK_DW_FIL_PROYECTO FOREIGN KEY (PROYECTO_ID) 
        REFERENCES DW_PROYECTOS (PROYECTO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DW_FIL_DATASET FOREIGN KEY (DATASET_ID) 
        REFERENCES DW_DATASETS (DATASET_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DW_FIL_CARGA FOREIGN KEY (CARGA_ID) 
        REFERENCES DW_CARGAS (CARGA_ID) ON DELETE CASCADE,
    CONSTRAINT CK_DW_FIL_CAPA CHECK (CAPA IN ('RAW', 'STAGING', 'ANALYTICS')),
    CONSTRAINT CK_DW_FIL_ESTADO CHECK (ESTADO_VALIDACION IN ('VALIDA', 'CORREGIDA', 'RECHAZADA'))
);

CREATE INDEX IDX_DW_FIL_DATASET_NUM ON DW_FILAS (DATASET_ID, NUMERO_FILA);
CREATE INDEX IDX_DW_FIL_PROY_FECHA ON DW_FILAS (PROYECTO_ID, FECHA_REGISTRO);
CREATE INDEX IDX_DW_FIL_V01 ON DW_FILAS (PROYECTO_ID, VARCHAR_01);
CREATE INDEX IDX_DW_FIL_V02 ON DW_FILAS (PROYECTO_ID, VARCHAR_02);
CREATE INDEX IDX_DW_FIL_N01 ON DW_FILAS (PROYECTO_ID, NUMERIC_01);
CREATE INDEX IDX_DW_FIL_D01 ON DW_FILAS (PROYECTO_ID, DATE_01);

