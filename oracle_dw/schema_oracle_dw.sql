-- ==============================================================================
-- TABLA 1: DW_PROYECTOS (MAESTRO DE PROYECTOS MULTI-TENANT)
-- ==============================================================================
CREATE TABLE DW_PROYECTOS (
    PROYECTO_ID          VARCHAR2(36) NOT NULL,
    CODIGO_PROYECTO      VARCHAR2(50) NOT NULL,
    NOMBRE               VARCHAR2(150) NOT NULL,
    DESCRIPCION          VARCHAR2(1000),
    CATEGORIA            VARCHAR2(80) DEFAULT 'GENERAL',
    ESTADO               VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_POR           VARCHAR2(120) NOT NULL,
    TOTAL_DATASETS       NUMBER(8) DEFAULT 0,
    TOTAL_REGISTROS      NUMBER(12) DEFAULT 0,
    FECHA_CREACION       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_DW_PROYECTOS PRIMARY KEY (PROYECTO_ID),
    CONSTRAINT UQ_DW_CODIGO_PROYECTO UNIQUE (CODIGO_PROYECTO),
    CONSTRAINT CK_DW_PROY_ESTADO CHECK (ESTADO IN ('ACTIVO', 'ARCHIVADO', 'SUSPENDIDO'))
);

CREATE INDEX IDX_DW_PROY_CREADO_POR ON DW_PROYECTOS (CREADO_POR);
CREATE INDEX IDX_DW_PROY_ESTADO ON DW_PROYECTOS (ESTADO);

-- ==============================================================================
-- TABLA 2: DW_ACCESOS (CONTROL DE ACCESO Y PERMISOS POR PROYECTO - RBAC)
-- ==============================================================================
CREATE TABLE DW_ACCESOS (
    ACCESO_ID            VARCHAR2(36) NOT NULL,
    PROYECTO_ID          VARCHAR2(36) NOT NULL,
    USUARIO_EMAIL        VARCHAR2(120) NOT NULL,
    USUARIO_NOMBRE       VARCHAR2(150),
    ROL                  VARCHAR2(30) DEFAULT 'ESTUDIANTE' NOT NULL,
    PUEDE_CARGAR         NUMBER(1) DEFAULT 1 NOT NULL,
    PUEDE_EDITAR         NUMBER(1) DEFAULT 0 NOT NULL,
    PUEDE_EXPORTAR       NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_ASIGNACION     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_DW_ACCESOS PRIMARY KEY (ACCESO_ID),
    CONSTRAINT FK_DW_ACC_PROYECTO FOREIGN KEY (PROYECTO_ID) 
        REFERENCES DW_PROYECTOS (PROYECTO_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_DW_ACC_PROY_USER UNIQUE (PROYECTO_ID, USUARIO_EMAIL),
    CONSTRAINT CK_DW_ACC_ROL CHECK (ROL IN ('ADMINISTRADOR', 'ANALISTA', 'ESTUDIANTE', 'LECTOR')),
    CONSTRAINT CK_DW_ACC_PUEDE_CARGAR CHECK (PUEDE_CARGAR IN (0, 1)),
    CONSTRAINT CK_DW_ACC_PUEDE_EDITAR CHECK (PUEDE_EDITAR IN (0, 1)),
    CONSTRAINT CK_DW_ACC_PUEDE_EXPORTAR CHECK (PUEDE_EXPORTAR IN (0, 1))
);

CREATE INDEX IDX_DW_ACC_EMAIL ON DW_ACCESOS (USUARIO_EMAIL);

-- ==============================================================================
-- TABLA 3: DW_DATASETS (CATÁLOGO DE CONJUNTOS DE DATOS CARGADOS)
-- ==============================================================================
