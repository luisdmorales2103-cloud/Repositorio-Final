    DESCRIPCION          VARCHAR2(500),
    NOMBRE_ARCHIVO_ORIG  VARCHAR2(255) NOT NULL,
    STORAGE_PATH_ORIG    VARCHAR2(500) NOT NULL,
    STORAGE_PROVIDER     VARCHAR2(30) DEFAULT 'LOCAL_CORPORATE' NOT NULL,
    FORMATO_ARCHIVO      VARCHAR2(20) NOT NULL,
